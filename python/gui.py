"""
gui.py
-------
Simple Tkinter GUI to showcase the final results.

IMPORTANT: This GUI does NOT train any model. It only READS the results
already generated by:
    1. python/data_analysis.py
    2. python/forecasting_validation.py
    3. python/inventory_analysis.py

Run those three scripts first (or run.py, which runs all of them), THEN
launch this GUI:
    python python/gui.py
"""

import json
import os
import subprocess
import sys
import tkinter as tk
from tkinter import ttk, messagebox

import pandas as pd

# Absolute path to the project root (one level up from this file's folder),
# so this works no matter what folder you're in when you launch it.
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(PROJECT_ROOT, "outputs")


def load_results():
    """Load the pre-generated result files. Returns None if not yet generated."""
    required = [
        os.path.join(OUT_DIR, "forecast_summary.json"),
        os.path.join(OUT_DIR, "inventory_summary.json"),
        os.path.join(OUT_DIR, "model_comparison.csv"),
    ]
    if not all(os.path.exists(p) for p in required):
        return None

    with open(os.path.join(OUT_DIR, "forecast_summary.json")) as f:
        forecast_summary = json.load(f)
    with open(os.path.join(OUT_DIR, "inventory_summary.json")) as f:
        inventory_summary = json.load(f)
    comparison_df = pd.read_csv(os.path.join(OUT_DIR, "model_comparison.csv"))

    return forecast_summary, inventory_summary, comparison_df


class RetailForecastApp:
    def __init__(self, root):
        self.root = root
        self.root.title("Retail Demand Forecasting & Inventory Optimization")
        self.root.geometry("620x560")
        self.root.configure(bg="#F5F5F5")

        title = tk.Label(
            root, text="Retail Demand Forecasting & Inventory Optimization",
            font=("Segoe UI", 14, "bold"), bg="#F5F5F5", fg="#222222"
        )
        title.pack(pady=(15, 5))

        subtitle = tk.Label(
            root, text="Case Study: RapidMiner-Based Retail Demand Forecasting",
            font=("Segoe UI", 9), bg="#F5F5F5", fg="#555555"
        )
        subtitle.pack(pady=(0, 15))

        # ---- Forecast Summary section ----
        self.forecast_frame = tk.LabelFrame(
            root, text="Forecast Summary", font=("Segoe UI", 10, "bold"),
            bg="#FFFFFF", padx=15, pady=10
        )
        self.forecast_frame.pack(fill="x", padx=20, pady=8)

        self.lbl_forecast_demand = self._add_row(self.forecast_frame, "Forecasted Demand (next day):", 0)
        self.lbl_current_inventory = self._add_row(self.forecast_frame, "Current Inventory:", 1)
        self.lbl_gap = self._add_row(self.forecast_frame, "Inventory Gap:", 2)
        self.lbl_days_supply = self._add_row(self.forecast_frame, "Days of Supply Remaining:", 3)
        self.lbl_recommendation = self._add_row(self.forecast_frame, "Recommendation:", 4, wrap=True)

        # ---- Model Comparison section ----
        self.model_frame = tk.LabelFrame(
            root, text="Model Comparison", font=("Segoe UI", 10, "bold"),
            bg="#FFFFFF", padx=15, pady=10
        )
        self.model_frame.pack(fill="x", padx=20, pady=8)

        self.lbl_arima = self._add_row(self.model_frame, "ARIMA (MAE / RMSE / MAPE):", 0)
        self.lbl_hw = self._add_row(self.model_frame, "Holt-Winters (MAE / RMSE / MAPE):", 1)
        self.lbl_best = self._add_row(self.model_frame, "Best Model Selected:", 2)

        # ---- Buttons ----
        btn_frame = tk.Frame(root, bg="#F5F5F5")
        btn_frame.pack(pady=20)

        self.btn_generate = tk.Button(
            btn_frame, text="Generate Forecast", font=("Segoe UI", 10),
            width=18, command=self.refresh_results, bg="#4C72B0", fg="white"
        )
        self.btn_generate.grid(row=0, column=0, padx=8)

        self.btn_plot = tk.Button(
            btn_frame, text="View Forecast Plot", font=("Segoe UI", 10),
            width=18, command=self.view_plot, bg="#55A868", fg="white"
        )
        self.btn_plot.grid(row=0, column=1, padx=8)

        # ---- Status bar ----
        self.status = tk.Label(
            root, text="", font=("Segoe UI", 8, "italic"), bg="#F5F5F5", fg="#777777"
        )
        self.status.pack(side="bottom", pady=8)

        self.refresh_results()

    def _add_row(self, parent, label_text, row, wrap=False):
        lbl = tk.Label(parent, text=label_text, font=("Segoe UI", 9, "bold"),
                        bg="#FFFFFF", anchor="w")
        lbl.grid(row=row, column=0, sticky="w", pady=4)

        val = tk.Label(parent, text="-", font=("Segoe UI", 9), bg="#FFFFFF",
                        anchor="w", justify="left",
                        wraplength=320 if wrap else 0)
        val.grid(row=row, column=1, sticky="w", padx=(10, 0), pady=4)
        return val

    def refresh_results(self):
        """
        'Generate Forecast' button: reads the latest already-generated
        result files (does NOT retrain models live - that is done by
        running the pipeline scripts, per the project requirements).
        """
        results = load_results()
        if results is None:
            messagebox.showwarning(
                "No results found",
                "No generated results found in outputs/.\n\n"
                "Please run the pipeline first from the project root:\n"
                "  python run.py\n\n"
                "Then click 'Generate Forecast' again."
            )
            self.status.config(text="No results found - run the pipeline first.")
            return

        forecast_summary, inventory_summary, comparison_df = results

        self.lbl_forecast_demand.config(
            text=f"{inventory_summary['next_day_forecast_demand']:.0f} units "
                 f"(on {forecast_summary['forecast_period'].split(' to ')[0]})"
        )
        self.lbl_current_inventory.config(
            text=f"{inventory_summary['current_inventory']:.0f} units "
                 f"(as of {inventory_summary['inventory_snapshot_date']})"
        )
        gap = inventory_summary["next_day_inventory_gap"]
        self.lbl_gap.config(text=f"{gap:+.0f} units")
        self.lbl_days_supply.config(text=f"{inventory_summary['days_of_supply_remaining']} days")
        self.lbl_recommendation.config(text=inventory_summary["next_day_recommendation"])

        comp = comparison_df.set_index("Model")
        if "ARIMA" in comp.index:
            r = comp.loc["ARIMA"]
            self.lbl_arima.config(text=f"{r['MAE']:.1f} / {r['RMSE']:.1f} / {r['MAPE']:.1f}%")
        if "Holt-Winters" in comp.index:
            r = comp.loc["Holt-Winters"]
            self.lbl_hw.config(text=f"{r['MAE']:.1f} / {r['RMSE']:.1f} / {r['MAPE']:.1f}%")

        self.lbl_best.config(text=forecast_summary["best_model"])

        self.status.config(text="Results loaded from outputs/ (last generated by running the pipeline).")

    def view_plot(self):
        plot_path = os.path.join(OUT_DIR, "forecast_plot.png")
        if not os.path.exists(plot_path):
            messagebox.showwarning("Plot not found", "Please run the pipeline first to generate forecast_plot.png.")
            return

        # Open with the OS default image viewer
        try:
            if sys.platform.startswith("win"):
                os.startfile(plot_path)
            elif sys.platform == "darwin":
                subprocess.run(["open", plot_path])
            else:
                subprocess.run(["xdg-open", plot_path])
        except Exception as e:
            messagebox.showerror("Could not open plot", str(e))


if __name__ == "__main__":
    root = tk.Tk()
    app = RetailForecastApp(root)
    root.mainloop()
